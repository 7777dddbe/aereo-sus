import * as THREE from 'three';
import { AircraftModel } from '../../src/aircraft/model.js';
import { Environment } from '../../src/world/environment.js';
import { Systems } from '../../src/aircraft/systems.js';

const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
renderer.setSize(1280, 720);
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure = 0.55;
renderer.shadowMap.enabled = true;
renderer.shadowMap.type = THREE.PCFSoftShadowMap;
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
const env = new Environment(scene, renderer, { quality: 'medium' });
const camera = new THREE.PerspectiveCamera(40, 1280 / 720, 0.1, 100000);
const model = new AircraftModel({ quality: 'medium' });
scene.add(model.group);
const ground = new THREE.Mesh(new THREE.PlaneGeometry(400, 400), new THREE.MeshStandardMaterial({ color: 0x55604a, roughness: 1 }));
ground.rotation.x = -Math.PI / 2;
ground.position.y = -3.0;
ground.receiveShadow = true;
scene.add(ground);
const sys = new Systems();
const fmStub = { surf: { elev: 0, ail: 0, rud: 0 }, out: { tas: 0, gearCompress: [0, 0, 0], wheelSpeed: [0, 0, 0] } };
window.setView = (az, el, dist, opts = {}) => {
  sys.gearPos = opts.gear ?? 1;
  sys.flapPos = opts.flap ?? 0;
  sys.probePos = opts.probe ?? 0;
  sys.doorOpen = opts.doors ?? [0, 0, 0, 0];
  fmStub.surf = opts.surf || { elev: 0, ail: 0, rud: 0 };
  sys.engines.forEach((e) => { e.np = opts.np ?? 0; e.running = true; });
  ground.visible = opts.ground !== false;
  model.update(0.016, sys, fmStub);
  const t = new THREE.Vector3(...(opts.target || [0, 0.5, 0]));
  camera.position.set(t.x + dist * Math.cos(el) * Math.sin(az), t.y + dist * Math.sin(el), t.z + dist * Math.cos(el) * Math.cos(az));
  camera.lookAt(t);
  env.update(0.016, new THREE.Vector3(), camera.position);
  renderer.render(scene, camera);
  return true;
};
window.ready = true;
import { Cockpit } from '../../src/aircraft/cockpit.js';
const cockpit = new Cockpit({ quality: 'medium' });
model.group.add(cockpit.group);
model.setInterior(false);
window.setCockpit = (yaw, pitch, fov = 70, opts = {}) => {
  model.setInterior(true);
  sys.gearPos = 1; sys.flapPos = 15; sys.flapIndex = 2;
  sys.engines.forEach((e) => { e.np = 100; e.running = true; e.torque = 60; e.itt = 650; e.nh = 92; e.ff = 400; e.lever = 0.6; });
  sys.tanks = [1200, 1300, 900, 1500];
  const fm = { surf: { elev: 0, ail: 0, rud: 0 }, ctl: { elevator: 0.2, aileron: 0.3, rudder: 0.2, tiller: 0 }, out: { tas: 50, ias: 55, alt: 120, vs: -2, pitch: 0.06, roll: 0.25, heading: 1.2, turnRate: 0.04, ny: 0.05, nz: 1.1, radAlt: 60, scoopRate: 0, gearCompress: [0, 0, 0], wheelSpeed: [0, 0, 0] } };
  model.update(0.016, sys, fm);
  cockpit.update(0.2, fm, sys, 1);
  camera.fov = fov; camera.updateProjectionMatrix();
  camera.position.copy(cockpit.eye);
  camera.rotation.set(0, 0, 0, 'YXZ');
  camera.rotation.order = 'YXZ';
  camera.rotation.y = yaw; camera.rotation.x = pitch;
  ground.visible = true;
  env.update(0.016, new THREE.Vector3(), camera.position);
  renderer.render(scene, camera);
  return true;
};
